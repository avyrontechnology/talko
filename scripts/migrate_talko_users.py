"""Ops migration: talko_users (Mongo) -> console users (Postgres).

WHAT IT DOES
  1. Reads every doc in talko `talko_users`.
  2. Emits ONE idempotent SQL file (ON CONFLICT DO NOTHING) inserting
     console_users rows: email/name/phone, role mapped to console
     hierarchy, partner via --partner-map, NO password (PBKDF2 cannot
     convert to bcrypt) — migrated users MUST reset passwords.
  3. Emits the partner-map CSV template when --partner-map is absent.

ROLE MAP (locked): superadmin->hierarchy 0, maintainer->3, viewer->8.
Partner map CSV format:  talko_partner_int,console_partner_uuid

USAGE
  python3 migrate_talko_users.py --mongo-uri mongodb://... --db talkoservice \\
      --partner-map partner_map.csv --out console_users_seed.sql
  python3 migrate_talko_users.py --partner-map-template

Run the SQL with psql on the console DB, then flip TALKO_CENTRAL_LOGIN=true.
"""
import argparse
import csv
import sys
import uuid

ROLE_TO_HIERARCHY = {"superadmin": 0, "maintainer": 3, "viewer": 8}
# System default role slugs expected in console (seeded by roles_gen).
HIERARCHY_TO_ROLE_SLUG = {0: "superadmin", 3: "maintainer", 8: "viewer"}


def q(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--mongo-uri", default="")
    ap.add_argument("--db", default="talkoservice")
    ap.add_argument("--partner-map", default="")
    ap.add_argument("--out", default="console_users_seed.sql")
    ap.add_argument("--partner-map-template", action="store_true")
    args = ap.parse_args()

    if args.partner_map_template:
        print("talko_partner_int,console_partner_uuid")
        print("0,00000000-0000-0000-0000-000000000000  # replace: default/internal partner")
        return

    if not args.mongo_uri or not args.partner_map:
        print("Need --mongo-uri and --partner-map (or --partner-map-template).")
        sys.exit(2)

    pmap: dict[str, str] = {}
    with open(args.partner_map, newline="") as f:
        for row in csv.DictReader(f):
            k = (row.get("talko_partner_int") or "").strip()
            v = (row.get("console_partner_uuid") or "").strip()
            if k and v and not k.startswith("#"):
                pmap[k] = v

    from pymongo import MongoClient

    docs = list(
        MongoClient(args.mongo_uri)[args.db]["talko_users"].find({}).sort("email", 1)
    )
    print(f"Read {len(docs)} talko users.")

    lines = [
        "-- Generated by migrate_talko_users.py — idempotent (email unique).",
        "-- Migrated users have NO password: force reset on first login.",
        "BEGIN;",
    ]
    skipped: list[str] = []
    for d in docs:
        email = (d.get("email") or "").strip().lower()
        if not email:
            skipped.append(str(d.get("_id")))
            continue
        role = (d.get("role") or "viewer").strip().lower()
        hierarchy = ROLE_TO_HIERARCHY.get(role, 8)
        pid = d.get("partner_id")
        console_partner = pmap.get(str(pid), "") if pid is not None else ""
        if pid is not None and not console_partner:
            skipped.append(f"{email} (partner {pid} not mapped)")
            continue
        name = (d.get("name") or email.split("@")[0]).replace("'", "''")
        phone = (d.get("phone") or "").replace("'", "''")
        is_active = "TRUE" if d.get("is_active", True) else "FALSE"
        lines.append(
            "INSERT INTO console_users (id, name, email, phone_number, hashed_password,"
            " partner_id, role_id, is_active, is_deleted, created_at)"
            f" SELECT '{uuid.uuid4()}', '{name}', '{email}', "
            f"{('NULL' if not phone else q(phone))}, '', "
            f"{('NULL' if not console_partner else q(console_partner))}, "
            f"(SELECT id FROM console_role WHERE hierarchy = {hierarchy} AND partner_id IS NULL),"
            f" {is_active}, FALSE, "
            f"{int(__import__('time').time() * 1000)}"
            " WHERE NOT EXISTS (SELECT 1 FROM console_users WHERE email = "
            f"{q(email)});"
        )
    lines.append("COMMIT;")
    with open(args.out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"Wrote {args.out} ({len(lines) - 3} inserts, {len(skipped)} skipped).")
    for s in skipped:
        print("  SKIP:", s)
    print("After applying: users reset passwords, then set TALKO_CENTRAL_LOGIN=true.")


if __name__ == "__main__":
    main()
